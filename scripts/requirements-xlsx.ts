// Exports docs/d6.4-requirements-traceability.md to an .xlsx for stakeholders who want the
// matrix in Excel (filtering/sorting/sharing) rather than reading it on GitHub. One-way export
// only — the markdown file (extracted from the D6.4 PDF, hand-assessed) stays the source of
// truth; this is not re-imported.
import fs from 'node:fs';
import path from 'node:path';
import ExcelJS from 'exceljs';

const SOURCE_DOC = path.resolve(
  __dirname,
  '../docs/d6.4-requirements-traceability.md',
);
const OUTPUT_FILE = path.resolve(
  __dirname,
  '../docs/d6.4-requirements-traceability.xlsx',
);

type Row = {
  section: string;
  id: string;
  level: string;
  requirement: string;
  status: string;
  note: string;
};

function parseRows(): Row[] {
  const lines = fs.readFileSync(SOURCE_DOC, 'utf8').split('\n');
  const rows: Row[] = [];
  let section = '';

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const heading = /^(##|###)\s+(.*)$/.exec(line);
    if (heading) {
      section = heading[2].trim();
      continue;
    }

    if (
      !/^\|\s*ID\s*\|\s*Level\s*\|\s*Requirement\s*\|\s*Status\s*\|\s*Note\s*\|/.test(
        line,
      )
    )
      continue;
    // Table header found; skip it and the separator row, then read data rows until the table ends.
    i += 2;
    for (; i < lines.length; i++) {
      const row = lines[i];
      if (!row.startsWith('|')) {
        i--;
        break;
      }
      const cells = row
        .split('|')
        .slice(1, -1)
        .map((c) => c.trim());
      if (cells.length < 5) continue;
      const [id, level, requirement, status, note] = cells;
      rows.push({ section, id, level, requirement, status, note });
    }
  }

  return rows;
}

async function main() {
  const rows = parseRows();

  const workbook = new ExcelJS.Workbook();

  const sheet = workbook.addWorksheet('Requirements', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });
  sheet.columns = [
    { header: 'Section', key: 'section', width: 42 },
    { header: 'ID', key: 'id', width: 12 },
    { header: 'Level', key: 'level', width: 12 },
    { header: 'Requirement', key: 'requirement', width: 70 },
    { header: 'Status', key: 'status', width: 10 },
    { header: 'Note', key: 'note', width: 90 },
  ];
  sheet.getRow(1).font = { bold: true };
  sheet.addRows(rows);
  sheet.autoFilter = { from: 'A1', to: 'F1' };
  for (const row of sheet.getRows(2, rows.length) ?? []) {
    row.getCell('requirement').alignment = { wrapText: true, vertical: 'top' };
    row.getCell('note').alignment = { wrapText: true, vertical: 'top' };
    row.getCell('status').alignment = { horizontal: 'center' };
  }

  const legend = workbook.addWorksheet('Legend');
  legend.columns = [
    { header: 'Symbol', key: 'symbol', width: 10 },
    { header: 'Meaning', key: 'meaning', width: 80 },
  ];
  legend.getRow(1).font = { bold: true };
  legend.addRows([
    { symbol: '✅', meaning: 'Implemented' },
    { symbol: '◑', meaning: 'Partial' },
    { symbol: '✗', meaning: 'Not implemented' },
    { symbol: '⏳', meaning: 'Blocked on an external dependency' },
    {
      symbol: '—',
      meaning:
        'Out of scope or not code-assessable (legal/organisational obligation, infrastructure/deployment concern, or requires a real external system this project can’t stand up alone)',
    },
  ]);
  legend.addRow({});
  legend.addRow({
    symbol: '',
    meaning:
      'Source: docs/d6.4-requirements-traceability.md, generated by scripts/requirements-xlsx.ts. That markdown file is the source of truth — edit it there, then re-run npm run requirements:xlsx. This is an unofficial community project; nothing here is compliance advice.',
  });

  await workbook.xlsx.writeFile(OUTPUT_FILE);
  console.log(
    `Written ${rows.length} requirements to ${path.relative(path.resolve(__dirname, '..'), OUTPUT_FILE)}`,
  );
}

main();
